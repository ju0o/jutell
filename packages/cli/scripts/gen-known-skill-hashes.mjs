// Regenerates src/installer/known-skill-hashes.ts: sha256 of every version of every Skill file
// JuTell ever shipped (from git history). Used to recognise JuTell-installed files on upgrade
// when the install manifest (cli-install.json) has no record of them, e.g. installs from 2.0.x.
// Run from the repo: node packages/cli/scripts/gen-known-skill-hashes.mjs
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const git = (...args) => execFileSync('git', args, { cwd: path.resolve(packageRoot, '..', '..'), encoding: 'buffer', maxBuffer: 64 * 1024 * 1024 });
const skillDir = '.agents/skills/beginner-bridge';
const hashes = new Set();
const log = git('log', '--all', '--format=%H', '--', skillDir).toString('utf8').trim().split('\n').filter(Boolean);
for (const commit of log) {
  const files = git('ls-tree', '-r', '--name-only', commit, '--', skillDir).toString('utf8').trim().split('\n').filter(Boolean);
  for (const file of files) hashes.add(createHash('sha256').update(git('show', `${commit}:${file}`)).digest('hex'));
}
const body = `// Generated by scripts/gen-known-skill-hashes.mjs. Do not edit by hand.\n// sha256 of Skill files shipped by earlier JuTell versions.\nexport const KNOWN_SHIPPED_SKILL_HASHES: ReadonlySet<string> = new Set([\n${[...hashes].sort().map((hash) => `  '${hash}',`).join('\n')}\n]);\n`;
writeFileSync(path.join(packageRoot, 'src', 'installer', 'known-skill-hashes.ts'), body);
console.log(`${hashes.size} hashes from ${log.length} commits`);
